select
    try_cast(fixture_id as bigint)                    as fixture_id,
    try_cast(league_id as bigint)                     as league_id,
    try_cast(season_id as bigint)                     as season_id,
    try_cast(team_id as bigint)                       as team_id,
    try_cast(try_cast(player_id as double) as bigint) as player_id,
    try_cast(try_cast(posisi as double) as bigint)    as posisi_id,
    liga,
    musim,
    home_team,
    away_team,
    player_name,
    try_cast(tanggal as timestamp)                    as match_at,
    try_cast(status_pemain as bigint)                 as status_pemain,
    try_cast(minutes_played as double)                as minutes_played,
    try_cast(rating as double)                        as rating,
    try_cast(goals as double)                         as goals,
    try_cast(assists as double)                       as assists,
    try_cast(saves as double)                         as saves,
    try_cast(shots_total as double)                   as shots_total,
    try_cast(passes as double)                        as passes,
    try_cast(tackles as double)                       as tackles,
    try_cast(interceptions as double)                 as interceptions,
    try_cast(xg as double)                            as xg,
    try_cast(xgot as double)                          as xgot,
    try_cast(left(diunduh_pada, 19) as timestamp)     as extracted_at,
    _loaded_at
from {{ source('raw', 'player_stats') }}
